library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.NUMERIC_STD.ALL;

entity simple_pwm is
    Port ( 
        clk     : in  STD_LOGIC;  -- FPGA ??????? (?? 50MHz)
        pwm_out : out STD_LOGIC   -- ????????? PWM ??
    );
end simple_pwm;

architecture Behavioral of simple_pwm is
    -- ???? 16 ???????????????? 0 (Xilinx FPGA ?????????)
    signal counter : unsigned(15 downto 0) := (others => '0');
    
    -- ????????16 ????? 65535?
    -- ????? 16384??? 16384 / 65536 = 25% ???
    constant DUTY_CYCLE : unsigned(15 downto 0) := to_unsigned(16384, 16);
begin
process(clk)
    begin
        if rising_edge(clk) then
            -- ??????????????? 0
            counter <= counter + 1;
            
            -- PWM ??????????????????????????
            if counter < DUTY_CYCLE then
                pwm_out <= '1';
            else
                pwm_out <= '0';
            end if;
        end if;
    end process;

end Behavioral;